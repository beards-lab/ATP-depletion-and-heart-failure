%% RunDrugCombos.m -- multi-lever drug hypotheses that single levers cannot reproduce (isoproterenol,
% diltiazem low dose), on both cores. Each combo = cellstr of 'lever=f' terms applied in sequence.
here = fileparts(mfilename('fullpath'));  res = fullfile(here, 'results');
L = drugLevers();  LN = {L.name};
combos = { ...
  'iso: Ca x1.5',                              {'CaAmp=1.5'}; ...
  'iso: Ca x1.5, decay x0.8',                  {'CaAmp=1.5', 'CaDecay=0.8'}; ...
  'iso: Ca x1.5, decay x0.8, SRXrel x2',       {'CaAmp=1.5', 'CaDecay=0.8', 'SRXrel=2'}; ...
  'iso: Ca x1.5, decay x0.8, SRXrel x2, koff x1.5 (cTnI)', {'CaAmp=1.5', 'CaDecay=0.8', 'SRXrel=2', 'tf_koff=1.5'}; ...
  'iso: Ca x2, decay x0.8, SRXrel x2',         {'CaAmp=2', 'CaDecay=0.8', 'SRXrel=2'}; ...
  'iso: Ca x1.3, decay x0.8, SRXrel x2, MgATP 8 (ref)', {'CaAmp=1.3', 'CaDecay=0.8', 'SRXrel=2'}; ...
  'dilt low: Ca x0.9, decay x1.3',             {'CaAmp=0.9', 'CaDecay=1.3'}; ...
  'dox/suni: Ca x0.8, kstiff x0.7',            {'CaAmp=0.8', 'kstiff=0.7'}; ...
  'dox/suni: Ca x0.8, MgATP 2',                {'CaAmp=0.8', 'MgATP=2'}; ...
  'dox/suni: tf_kon x0.85, MgATP 2',           {'tf_kon=0.85', 'MgATP=2'}; ...
  'mava: ka x0.5, SRXstab x1.5',               {'ka=0.5', 'SRXstab=1.5'}; ...
  'mava: ka x0.5, k1 x0.3',                    {'ka=0.5', 'k1=0.3'}};
cores = {'t1_isoT', 's3_free'};  T = table();
for c = 1:numel(cores)
    [base, th, tb] = drugBase(cores{c});
    [F0, S0] = simHumanTwitch(base, th, tb);  m0 = twitchShape(tb, F0);
    R = cell(size(combos, 1), 1);
    parfor k = 1:size(combos, 1)
        b = base;  t = th;
        for j = 1:numel(combos{k, 2})
            p = split(combos{k, 2}{j}, '=');  i = find(strcmp(LN, p{1}), 1);
            [b, t] = L(i).apply(b, t, str2double(p{2}));
        end
        [F, S] = simHumanTwitch(b, t, tb);  m = twitchShape(tb, F);
        R{k} = table(cores(c), combos(k, 1), 100*(m.Fpk/m0.Fpk - 1), 1e3*(m.TTP - m0.TTP), 1e3*(m.RT50 - m0.RT50), 1e3*(m.RT90 - m0.RT90), trapz(tb, S.R2T), S.SRX(1), max(S.gate), ...
            'VariableNames', {'core', 'combo', 'dF', 'dTTP', 'dRT50', 'dRT90', 'ATPbeat', 'SRXdia', 'gatePk'});
    end
    T = [T; vertcat(R{:})];
end
disp(T);  writetable(T, fullfile(res, 'combos.csv'));  save(fullfile(res, 'combos.mat'), 'T');

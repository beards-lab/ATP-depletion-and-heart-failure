function A = ablationSpec()
%ABLATIONSPEC  The one-at-a-time mechanism ablation arms, 8 mM only.
%
%   A = ablationSpec() returns a struct array, one element per arm:
%
%     A(k).id     short id ('B4'), used in the report
%     A(k).name   tag stem; the arm writes params/abl_<name>_{opt.m,state.mat,iter/}
%     A(k).set    {field, value, field, value, ...} applied to the base params0.
%                 This is BOTH the switch flip AND any seed value the mechanism
%                 needs to be non-inert (see trap T1 in plan.md).
%     A(k).add    params that become live -> added to cfg.pool
%     A(k).drop   params that become dead -> removed from cfg.pool
%     A(k).comp   compensators: the parameters that must be free for the
%                 mechanism to be allowed to be absorbed. add+comp become
%                 cfg.compulsory for that arm (trap T3: anything else is
%                 touched ~1 round in 16 and is effectively frozen).
%     A(k).note   one line, what the arm is asking
%
%   Base point: params/floored_seed.m (cost 0.9081). See plan.md §0.
%
%   SCOPE: one-at-a-time, 8 mM only. Excluded by that scope:
%     - UseAtpDetachR2, UseAtpKmsrd: both gates are normalised to 1 at
%       MgATP_ref = 8, so they are identically inert here. 2 mM worktree only.
%     - UseD0State: nearly inert at 8 mM (k_D0T*8/8.15) and its inflow needs
%       D0FromR2/k2rip. 2 mM worktree only.
%     - UseTitinIdentifiedPassive / UseTitinInterpolation: need TitinTable,
%       not confirmed present.
%     - dead switches, numerics, protocol switches, 3-state, alternative
%       rate-law families: plan.md §3.
%
%   See also: RunAblationPreflight, RunAblationArm, plan.md

A = struct('id',{},'name',{},'set',{},'add',{},'drop',{},'comp',{},'note',{},'scale',{});

% =====================================================================
% TIER A -- nominally on, plausibly inert. Expect delta ~ 0.
% =====================================================================
A = iAdd(A,'A1','occupancy_off', ...
    {'UseGlobalOccupancySaturation',0}, ...
    {}, {'P_bound_max'}, {'ka','A0'}, ...
    'P_bound_max=1.13 vs prior 0.12-0.15: a flat x0.87 on ka. Free to delete?');

A = iAdd(A,'A2','dynpassive_off', ...
    {'UseDynamicPassive',0}, ...
    {}, {}, {'eta_M','k_pas','kSE_M'}, ...
    'on with c_titin_visc=0, i.e. exactly inert. Confirm and delete.');

A = iAdd(A,'A3','occupancy_langmuir', ...
    {'OccupancyForm','langmuir'}, ...
    {}, {}, {'P_bound_max','ka'}, ...
    'form test: 1/(1+P/Pmax) instead of 1-P/Pmax.');

A = iAdd(A,'A4','regavail_bidirectional', ...
    {'RegAvailShorteningOnly',0}, ...
    {}, {}, {'A0','v_ref_reg','tau_reg','ka'}, ...
    'availability recovers on lengthening too; the directional version was the F-V fix.');

A = iAdd(A,'A5','halfactive_SR', ...
    {'useHalfActiveForSR',1}, ...
    {}, {}, {'sigma2','sigma_srd1','ksr0','kmsrd'}, ...
    'thick filament senses F_active/2+F_passive instead of F_total.');

% =====================================================================
% TIER B -- on and load-bearing. The real ablations.
% =====================================================================
A = iAdd(A,'B1','regavail_off', ...
    {'UseRegistrationAvailability',0}, ...
    {}, {'A0','v_ref_reg','tau_reg'}, ...
    {'ka','k2','kA2re','PieceWiseStrainDep2X_logOffset','PieceWiseStrainDep2X__3','PieceWiseStrainDep2Params__4'}, ...
    'drop the sliding-availability gate; F-V shape must be carried by R2 strain law. State dim -1.');

A = iAdd(A,'B2','loadrealign_off', ...
    {'UseLoadRealign',0}, ...
    {}, {'k_cr','tau_cr','F_cr'}, ...
    {'kmsrd','tau_reg','kA2re','ksr2srd'}, ...
    'drop the load-dependent register deficit; slow re-stretch recovery must come from SRX. State dim -1.');

A = iAdd(A,'B3','a2reattach_off', ...
    {'UseA2Reattaching',0}, ...
    {}, {'kA2re','kA2hop','sA2hop'}, ...
    {'k1','k_1','kd','PieceWiseStrainDepR1DX_logOffset','PieceWiseStrainDepR1DParams__2'}, ...
    'drop PT->p2 valley fill and the high-strain hop.');

A = iAdd(A,'B4','srxadp_off', ...
    {'UseSuperRelaxedADP',0,'kmsr',10}, ...
    {'kmsr'}, {'kmsrd','ksrd2sr','ksr2srd','sigma_srd1','sigma_srd2'}, ...
    {'kmsr','sigma1','ksr0','sigma2'}, ...
    'delete the SRD pool. REQUIRES kmsr>0: with kmsr=0 SRX has no exit and becomes a black hole.');

A = iAdd(A,'B5','srx_off', ...
    {'UseSuperRelaxed',0,'UseSuperRelaxedADP',0,'SRXT_0',0,'SRXD_0',0}, ...
    {}, {'ksr0','sigma1','sigma2','ksr2srd','ksrd2sr','kmsrd','sigma_srd1','sigma_srd2'}, ...
    {'k1','k_1','ka','kd','k2'}, ...
    'no thick-filament regulation at all. SRXT_0/SRXD_0 zeroed or the initial pools are trapped forever.');

A = iAdd(A,'B6','negkstiff_off', ...
    {'UseNegativeKstiff',0}, ...
    {}, {'kstiff1_n','kstiff2_n'}, ...
    {'kstiff1','kstiff2','estiff','dr'}, ...
    'one stiffness for both signs of strain; hits the slack phase.');

A = iAdd(A,'B7','maxwell_off', ...
    {'UseMaxwellDashpot',0,'c_titin_visc',5}, ...
    {'c_titin_visc'}, {'kSE_M','eta_M','x_M_slack'}, ...
    {'c_titin_visc','k_pas','gamma','Lsc0'}, ...
    'titin viscoelasticity as a plain velocity term instead of a Maxwell element.');

A = iAdd(A,'B8','maxwell_bidirectional', ...
    {'UseMaxwellTensionOnly',0}, ...
    {}, {'x_M_slack'}, {'eta_M','kSE_M','k_pas'}, ...
    'let titin push as well as pull.');

A = iAdd(A,'B9','lattice_off', ...
    {'UseLatticeSpacing',0}, ...
    {}, {'d10_ref','SL_ref_lattice','R_thick','R_thin','d_optimal','sigma_lattice'}, ...
    {'L_thick','L_thin','L_hbare','ka'}, ...
    'f_lattice=1: length dependence of attachment must be carried by overlap alone.');

A = iAdd(A,'B10','overlapfactor_off', ...
    {'UseOverlapFactor',0}, ...
    {}, {}, {'ka','L_thick','L_thin'}, ...
    'stop renormalising N_overlap by the unattached pools.');

A = iAdd(A,'B11','overlap_off', ...
    {'UseOverlap',0}, ...
    {}, {'L_thick','L_hbare','L_thin'}, ...
    {'ka','d_optimal','sigma_lattice','d10_ref'}, ...
    'no filament overlap term; lattice spacing must carry all length dependence.');

A = iAdd(A,'B12','serialstiff_off', ...
    {'UseSerialStiffness',0}, ...
    {}, {'kSE','ekSE'}, {'mu','mu_neg','ka','k2'}, ...
    ['DEAD SWITCH (preflight 2026-09-11: exactly 0.0000). UseSerialStiffness is read NOWHERE in ' ...
     'dPUdT_CombinedTransitions -- only a comment there, a commented-out rmfield in evaluateModel ' ...
     'and its default in getParams. The serial elastic element is always on. Kept as a documented ' ...
     'finding; the campaign skips it. Dynamic range is demonstrated instead by B1/C8/B5.']);

A = iAdd(A,'B13','r1d_gaussian', ...
    {'UseStrainDep4R1D',1,'kd_sigma',0.01}, ...
    {'kd_sigma'}, ...
    {'PieceWiseStrainDepR1DX_logOffset','PieceWiseStrainDepR1DX__1','PieceWiseStrainDepR1DX__2', ...
     'PieceWiseStrainDepR1DX__3','PieceWiseStrainDepR1DX__4','PieceWiseStrainDepR1DParams__1', ...
     'PieceWiseStrainDepR1DParams__2','PieceWiseStrainDepR1DParams__3','PieceWiseStrainDepR1DParams__4'}, ...
    {'kd_sigma','kd','ka'}, ...
    'PARSIMONY: does the free-form R1D strain law earn its 9 parameters over one Gaussian width? kd_sigma has no default -- it is set here.');

% =====================================================================
% TIER C -- off, candidate additions. Every one needs a seed value (T1).
% =====================================================================
A = iAdd(A,'C1','srd_fixeddwell', ...
    {'SRDOutflowK',0.05}, ...
    {'SRDOutflowK'}, {}, {'SRDOutflowK','kmsrd','sigma_srd1','k_cr'}, ...
    'HIGHEST PRIOR VALUE. Fixed-dwell SRD drain: a bigger slug takes proportionally longer, which is the sign the rsK amplitude slope needs.');

A = iAdd(A,'C2','se_viscoelastic', ...
    {'UseViscoelasticSE',1,'c_SE_visc',0.01}, ...
    {'c_SE_visc'}, {}, {'c_SE_visc','kSE','ekSE','mu'}, ...
    'SE dashpot resists rapid lengthening -> aimed straight at the re-stretch overshoot.');

A = iAdd(A,'C3','a1kernel_on', ...
    {'UseA1AttachmentKernel',1}, ...
    {'A1AttachmentWidth'}, {}, {'A1AttachmentWidth','ka','dr','kstiff1'}, ...
    'distributed attachment over +-6 nm. The only ON arm whose parameter is already non-zero.');

A = iAdd(A,'C4','passive_for_SR', ...
    {'UsePassiveForSR',1}, ...
    {}, {}, {'ksr0','sigma2','sigma_srd1','kmsrd'}, ...
    'thick filament senses F_passive only. No new parameters.');

A = iAdd(A,'C5','limited_srd', ...
    {'UseLimitedSRDTransition',1,'Srd_max',20,'Srd_n',1}, ...
    {'Srd_max','Srd_n'}, {'sigma_srd2'}, {'Srd_max','Srd_n','kmsrd','ksr2srd'}, ...
    'PD->SRD flux is currently exactly zero (ksrd=0); this is the alternative way to give it one.');

A = iAdd(A,'C6','direct_srx', ...
    {'UseDirectSRXTransition',1}, ...
    {}, {}, {'ksr0','ksr2srd','kmsrd','sSRXrip'}, ...
    'route ALL R2 detachment into SRX (now partial at SRXFromR2HighStrain=0.21).');

A = iAdd(A,'C7','stretch_activation', ...
    {'UseStretchActivation',1,'k_SA',0.5}, ...
    {'k_SA'}, {}, {'k_SA','ka','kA2re'}, ...
    'ka rises with lengthening velocity.');

A = iAdd(A,'C8','velgauss_for_regavail', ...
    {'UseRegistrationAvailability',0,'UseVelGaussAttachment',1}, ...
    {'v_att_amplitude','v_att_center','v_att_sigma'}, {'A0','v_ref_reg','tau_reg'}, ...
    {'v_att_amplitude','v_att_center','v_att_sigma','ka','k2'}, ...
    'SUBSTITUTION: instantaneous velocity-Gaussian ka instead of the slow availability state.');

A = iAdd(A,'C9','vernier_on', ...
    {'UseVernierVelocity',1}, ...
    {'alpha_vernier','v_ref_vernier'}, {}, {'alpha_vernier','v_ref_vernier','ka'}, ...
    'third form of velocity-dependent attachment (saturating, not Gaussian).');

A = iAdd(A,'C10','a2recocking', ...
    {'UseA2MechanicalRecocking',1,'k2d',50,'drmr',0.01}, ...
    {'k2d','drmr'}, {}, {'k2d','drmr','kA2hop','k2'}, ...
    'ATP-free recocking of high-strain heads; overlaps kA2hop.');

A = iAdd(A,'C11','a2shift', ...
    {'UseA2AttachmentShift',1}, ...
    {'slope','s_threshold_R','d_actin'}, {}, {'slope','s_threshold_R','kA2hop','kd'}, ...
    'strained p2 heads hop to the neighbouring actin site; overlaps C10.');

A = iAdd(A,'C12','catchbond', ...
    {'UseCatchBond',1,'k_catch_bond',0.1}, ...
    {'k_catch_bond'}, {}, {'k_catch_bond','kd','k2','kA2re'}, ...
    'tried before: filled the valley but cost peak1_y. Re-test under the floored objective.');

A = iAdd(A,'C13','r2ceiling', ...
    {'UseR2Ceiling',1}, ...
    {'k2max','K_T2c'}, {}, {'k2max','k2','PieceWiseStrainDep2X_logOffset'}, ...
    'ceiling on the per-head detachment rate. NOT ATP-normalised, so it is testable at 8 mM.');

A = iAdd(A,'C14','a2popping', ...
    {'UseA2Popping',1,'pop_s',-0.05}, ...
    {'pop_s'}, {}, {'pop_s','kd'}, ...
    'hard removal of extreme-negative-strain heads; mostly a numerical guard. Low priority.');

% =====================================================================
% TIER R -- parameter revivals. Structural, but not Use* flags.
% =====================================================================
A = iAdd(A,'R1','kmsr_revive', ...
    {'kmsr',10}, ...
    {'kmsr'}, {}, {'kmsr','sigma1','ksr0','ksr2srd'}, ...
    'restore the direct force-dependent SRX->DRX return. kmsr=0 today, which also makes sigma1 dead.');

A = iAdd(A,'R2','ksrd_revive', ...
    {'ksrd',1}, ...
    {'ksrd'}, {}, {'ksrd','sigma_srd2','kmsrd'}, ...
    'restore first-order PD->SRD. ksrd=0 today, which also makes sigma_srd2 dead.');

A = iAdd(A,'R4','dA2re_revive', ...
    {'dA2re',0.005}, ...
    {'dA2re'}, {}, {'dA2re','kA2re','sA2hop'}, ...
    'give re-attached heads a non-zero landing strain.');

% =====================================================================
% SCALAR PRE-COMPENSATION
% =====================================================================
% The frozen-parameter preflight showed that a flip which changes a GAIN puts
% the model somewhere a 60-evaluation simplex cannot climb out of: removing the
% availability gate (A0 = 0.21) multiplies isometric attachment by ~5x and the
% cost goes to 46007, of which 45000 is coolDownLS -- an unbounded raw MSE on
% the cool-down trace (extractSlackAttributes.m:456), not a chi-2 term. Ranking
% arms on that is ranking how badly one guard term fired, and every gate-like
% mechanism would read as load-bearing purely from a scale offset.
%
% So each arm names ONE parameter that is line-searched over a multiplier grid
% before the simplex starts. The rule needs no per-arm judgement:
%
%   arms that ADD a mechanism  -> scale = add{1}, the mechanism's own strength.
%       The line search then answers "what strength does this mechanism want?"
%       rather than trusting the seed value guessed here.
%   arms that REMOVE one       -> scale = comp{1}, its natural gain absorber.
%
% The seed values below are therefore only the CENTRE of that grid, not a claim.
for k = 1:numel(A)
    if ~isempty(A(k).add)
        A(k).scale = A(k).add{1};
    elseif ~isempty(A(k).comp)
        A(k).scale = A(k).comp{1};
    else
        A(k).scale = '';
    end
end

% One override. C8 both DROPS the availability gate and ADDS the velocity
% Gaussian, and the gate is worth ~5x on isometric attachment (A0 = 0.21) while
% the Gaussian is worth tens of percent. Calibrating the Gaussian's amplitude
% would leave the 5x offset in place, so the gain absorber wins here.
A(strcmp({A.id},'C8')).scale = 'ka';

end

% -------------------------------------------------------------------------
function A = iAdd(A, id, name, setKV, add, drop, comp, note)
if mod(numel(setKV),2) ~= 0
    error('ablationSpec:set','arm %s: set must be field/value pairs', id);
end
k = numel(A) + 1;
A(k).id = id; A(k).name = name; A(k).set = setKV;
A(k).add = add; A(k).drop = drop; A(k).comp = comp; A(k).note = note;
A(k).scale = '';   % filled in by the pre-compensation block above
end

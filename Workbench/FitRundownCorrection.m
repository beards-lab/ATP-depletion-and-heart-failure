    outNameRaw = sprintf('Merged_RunDownCorrection_Model%g.txt', mi);
    outName = fullfile(dataDir, outNameRaw);

    Fcorr_i = models{mi}(params{mi}, F_rdact, L_ref) + Fpas;
    
    % Format: [Time(s), L, F]
    outData = [t_ref, L_ref, Fcorr_i];
    % if rewriteData
        writematrix(outData, outName, 'Delimiter', '\t');
        fprintf('  Saved %s\n', outNameRaw);
    % else
        % fprintf('  Skipping writing %s due to rewriteData = false \n', outNameRaw);
    % end
end

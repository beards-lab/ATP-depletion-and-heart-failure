%% FitRundownCorrection.m
% Fit a parametric correction  F_ref ≈ f(F_rd, SL)  from paired timecourse data.
%
% Four models of increasing complexity are fitted and compared.
% The key idea: the current scaleRundown uses a hand-tuned r0, k with no
% F-dependence. Here we let the data determine the best surface r(F, L).
%
% Requires in workspace (set by the "compensate for run-down" section):
%   F_refact, F_rdact, L_ref, t_ref   [active forces and SL on common t_ref]
%   r0, k, L0                          [current manual params, for comparison]
% -------------------------------------------------------------------------

%% --- 1. Data preparation ---------------------------------------------------
clear;close all;
dataDir = '../data/03 27 2026 M/';
% Generated by LoadAndPlot
data = load(fullfile(dataDir, 'AllDataMerged')).data;

refData = data(2);
t_ref = refData.t_fineShifted;
F_ref = refData.F_fineShifted;
L_ref = refData.L_fineShifted;
t_ref = refData.t_shifted_orig;
F_ref = refData.F_shifted_orig;
L_ref = refData.L_shifted_orig;


% run-down data
rundownData = data(4);
F_rd = interp1(rundownData.t_fineShifted, rundownData.F_fineShifted, t_ref);
L_rd = interp1(rundownData.t_fineShifted, rundownData.L_fineShifted, t_ref);

% passive reference
F_pas = 0; %interp1(data(5).t_fineShifted, data(5).F_fineShifted, t_ref);
F_rdact = F_rd - F_pas;
F_refact = F_ref - F_pas;

L0 = 1.0;
k  = -0.6;   % SL slope: increase until high-SL portion of corrected trace aligns with F_refact
r0 = (68)/(56);
r0=1.214286;
% r828 = 80.09/71;

Fmin_thresh = 3;    % [mN/mm² or kPa] min active force; below this the ratio is noise
validWin = isfinite(F_rdact) & isfinite(F_refact) & isfinite(L_ref) ...
      & F_rdact > Fmin_thresh & F_refact > 0 & t_ref > 68 & t_ref < 78;

trd = t_ref(validWin);
Frd  = F_rd(validWin);
Fref = F_ref(validWin);
Lobs = L_ref(validWin);
Fpas = 0;%F_pas(valid);

F0    = median(Frd);    % normalisation reference force
L0fit = 1.0;            % pivot SL (same as manual L0)

r_obs = Fref ./ Frd;   % observed pointwise correction ratio (for diagnostics)

fprintf('Fitting on %d points  (F0 = %.1f, L range = [%.3f, %.3f])\n', ...
    numel(Frd), F0, min(Lobs), max(Lobs));

%% --- 2. Model definitions --------------------------------------------------
%
% Each model has the signature  fcn(params, F, L) -> F_corrected
% All are multiplicative:  F_corr = F_rd * g(F_rd, L; params)
% except M4 which is a power law.
%
% M1  g = a + b*(L-L0)                           [2 params] — current, auto-fitted
% M2  g = a + b*(L-L0) + c*(F/F0-1)              [3 params] — adds F linear term
% M3  g = a + b*(L-L0) + c*(F/F0-1)
%           + d*(L-L0)*(F/F0-1)                  [4 params] — adds F×L interaction
% M4  F_corr = exp(a) * F^alpha * exp(b*(L-L0))  [3 params] — power-law in F
%
% Note on M4: alpha=1 reduces to a pure SL-exponential; alpha>1 means
% the correction amplifies high-force states more (or less for alpha<1).

fcn1 = @(p, F, L)  F .* (p(1) + p(2).*(L - L0fit));

fcn2 = @(p, F, L)  F .* (p(1) + p(2).*(L - L0fit) ...
                         + p(3).*(F./F0 - 1));

fcn3 = @(p, F, L)  F .* (p(1) + p(2).*(L - L0fit) ...
                         + p(3).*(F./F0 - 1) ...
                         + p(4).*(L - L0fit).*(F./F0 - 1));

fcn4 = @(p, F, L)  exp(p(1) + p(2).*log(F) + p(3).*(L - L0fit));
%  p(1)=log(A), p(2)=alpha, p(3)=b
%  => F_corr = A * F^alpha * exp(b*(L-L0))

%% --- 3. Fitting ------------------------------------------------------------

cost  = @(fcn, p) sum((fcn(p, Frd, Lobs) - Fref).^2);
opts  = optimset('Display','off','MaxFunEvals',1e5,'TolFun',1e-13,'TolX',1e-11);

% Sequential warm-start: each model initialises from the previous
p1 = fminsearch(@(p) cost(fcn1, p), [1.2, -0.6],        opts);
p2 = fminsearch(@(p) cost(fcn2, p), [p1, 0.0],          opts);
p3 = fminsearch(@(p) cost(fcn3, p), [p2, 0.0],          opts);
p4 = fminsearch(@(p) cost(fcn4, p), [log(p1(1)), 1, p1(2)], opts);

%% --- 4. Fit metrics --------------------------------------------------------

SS_tot = sum((Fref - mean(Fref)).^2);
R2fn   = @(Fp)  1 - sum((Fp - Fref).^2) / SS_tot;
RMSEfn = @(Fp)  sqrt(mean((Fp - Fref).^2));

models = {fcn1, fcn2, fcn3, fcn4};
params = {p1,   p2,   p3,   p4};
names  = {'M1: SL-linear', 'M2: +F linear', 'M3: +F×L interact', 'M4: power-law F'};
npar   = [2, 3, 4, 3];

R2s   = cellfun(@(f,p) R2fn(f(p, Frd, Lobs)),   models, params);
RMSEs = cellfun(@(f,p) RMSEfn(f(p, Frd, Lobs)), models, params);

% AIC (relative, for model selection)
n    = numel(Frd);
SSEs = cellfun(@(f,p) sum((f(p, Frd, Lobs) - Fref).^2), models, params);
AICs = n.*log(SSEs./n) + 2.*npar;
dAIC = AICs - min(AICs);

fprintf('\n%-24s  R²      RMSE    ΔAIC  params\n', 'Model');
fprintf('%s\n', repmat('-',1,72));
for mi = 1:4
    fprintf('%-24s  %.4f  %6.3f  %5.1f  %s\n', ...
        names{mi}, R2s(mi), RMSEs(mi), dAIC(mi), mat2str(params{mi}, 5));
end

%% --- 5. Visualisation ------------------------------------------------------
%
% Layout (2×3 tiles):
%   [1] Observed ratio scatter (F_rd, SL) coloured by r_obs
%   [2] M1 correction curves: F_corr vs F_rd at 4 SL levels
%   [3] M2   "
%   [4] M3   "
%   [5] M4   "
%   [6] Timecourse: reference vs all corrected traces

figure(302); clf;
tiledlayout(2, 2, 'TileSpacing', 'compact', 'Padding', 'compact');

% Four SL quantile levels for visualisation
SL_levels = quantile(Lobs, [0.10, 0.35, 0.65, 0.90]);
SL_levels = [0.8, 0.9, 1, 1.1, 1.2];
SL_labels = arrayfun(@(x) sprintf('SL = %.3f', x), SL_levels, 'UniformOutput', false);
cmap      = lines(4);
F_range   = linspace(Fmin_thresh, prctile(Frd, 98)*1.1, 300)';

% % -- Tile 1: ratio scatter ---------------------------------------------------
% nexttile;
% scatter(Frd, Lobs, 14, r_obs, 'filled', 'MarkerFaceAlpha', 0.35);
% cb = colorbar;
% cb.Label.String = 'r = F_{ref}/F_{rd}';
% xlabel('F_{rd}  (active)');
% ylabel('SL');
% title('Observed correction ratio');
% grid on;

% -- Tiles 2-5: correction curves per model ----------------------------------
for mi = 1:4
    nexttile;
    hold on;

    for si = 1:4
        Lfix   = SL_levels(si);
        Fcorr  = models{mi}(params{mi}, F_range, Lfix);
        ratio  = Fcorr ./ F_range;   % r = F_corr / F_rd for this SL slice
        yyaxis left;
        plot(F_range, Fcorr, '-', 'Color', cmap(si,:), 'LineWidth', 1.8, ...
            'DisplayName', SL_labels{si});
    end

    % Identity line (no correction)
    yyaxis left;
    plot(F_range([1 end]), F_range([1 end]), 'k--', 'LineWidth', 0.8, ...
        'HandleVisibility', 'off');
    ylabel('F_{corrected}');
    xlabel('F_{rd}  (active)');

    % Ratio on right axis
    yyaxis right;
    for si = 1:4
        Lfix  = SL_levels(si);
        Fcorr = models{mi}(params{mi}, F_range, Lfix);
        ratio = Fcorr ./ F_range;
        plot(F_range, ratio, '--', 'Color', cmap(si,:)*0.7, 'LineWidth', 0.9, ...
            'HandleVisibility', 'off');
    end
    ylabel('r = F_{corr}/F_{rd}');

    yyaxis left;
    legend('Location', 'northwest', 'FontSize', 7);
    title(sprintf('%s   R²=%.4f  ΔAIC=%+.0f', names{mi}, R2s(mi), dAIC(mi)));
    grid on;
end

%% -- Tile 6: Timecourse comparison -------------------------------------------
figure(44);clf;
nexttile;
hold on;

% Reference
plot(t_ref, F_refact + Fpas, 'k', 'LineWidth', 1.8, 'DisplayName', 'Reference');

% Current manual approach (inline: scaleRundown = F_rd * (r0 + k*(L-L0)))
% F_corr_manual = F_rdact .* (r0 + k .* (L_ref - L0));
% plot(t_ref, F_corr_manual + Fpas, 'b--', 'LineWidth', 1.0, ...
%     'DisplayName', sprintf('Manual r0=%.3f k=%.2f', r0, k));

% Fitted models
ls = {'-', '-', '-', '-'};
lw = [1.3, 1.3, 1.3, 1.8];
for mi = 1:4
    Fcorr_i = models{mi}(params{mi}, F_rdact, L_ref) + Fpas;
    plot(t_ref, Fcorr_i, ls{mi}, 'LineWidth', lw(mi), ...
        'DisplayName', sprintf('%s (R²=%.3f)', names{mi}, R2s(mi)));
end

xlabel('Time (s)');
ylabel('Active force');
title('Timecourse: reference vs corrected run-down');
legend('Location', 'best', 'FontSize', 6);
xlim([66.63 78.56]);
grid on;

%% --- 6. Best model summary -------------------------------------------------

[~, best] = min(dAIC);
fprintf('\nBest model by AIC: %s\n', names{best});
fprintf('  params = %s\n', mat2str(params{best}, 6));

% Build a ready-to-use anonymous function for downstream use:
fprintf('\nTo apply the best correction in your script:\n');
switch best
    case 1
        fprintf('  p = %s;\n', mat2str(p1,5));
        fprintf('  F_corrected = F_rdact .* (p(1) + p(2).*(L_ref - %.2f));\n', L0fit);
    case 2
        fprintf('  F0 = %.4g;\n', F0);
        fprintf('  p  = %s;\n', mat2str(p2,5));
        fprintf('  F_corrected = F_rdact .* (p(1) + p(2).*(L_ref - %.2f) + p(3).*(F_rdact/F0 - 1));\n', L0fit);
    case 3
        fprintf('  F0 = %.4g;\n', F0);
        fprintf('  p  = %s;\n', mat2str(p3,5));
        fprintf(['  F_corrected = F_rdact .* (p(1) + p(2).*(L_ref - %.2f) + p(3).*(F_rdact/F0-1)' ...
                 ' + p(4).*(L_ref - %.2f).*(F_rdact/F0-1));\n'], L0fit, L0fit);
    case 4
        fprintf('  p  = %s;\n', mat2str(p4,5));
        fprintf('  F_corrected = exp(p(1) + p(2).*log(F_rdact) + p(3).*(L_ref - %.2f));\n', L0fit);
end

